function Cards() {
  const [open, setOpen] = useState<number | null>(null);

  return (
    <div className="cards">
      <h2>교육 카드</h2>
      <p className="hint">카드를 누르면 설명이 나온다.</p>
      <div className="grid">
        {cards.map((card, i) => (
          <div
            key={card.title}
            className={`card ${open === i ? 'open' : ''}`}
            onClick={() => setOpen(open === i ? null : i)}
          >
            <h3>{card.title}</h3>
            {open === i && <p>{card.body}</p>}
          </div>
        ))}
      </div>
    </div>
  );
}

export default Cards;
